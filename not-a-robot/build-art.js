// Embeds every art/**/*.svg into index.html between the ART markers as `const ART = {"cat/stand": "<svg…>", …}`.
// Run: node build-art.js [artDir=art] [htmlFile=index.html]   (re-run after any SVG changes)
const fs = require('fs'), path = require('path');
const root = path.resolve(__dirname, process.argv[2] || 'art'), art = {};
for (const dir of fs.readdirSync(root)) {
  const d = path.join(root, dir); if (!fs.statSync(d).isDirectory()) continue;
  for (const f of fs.readdirSync(d)) if (f.endsWith('.svg'))
    art[dir + '/' + f.slice(0, -4)] = fs.readFileSync(path.join(d, f), 'utf8').replace(/<\?xml[^>]*>/, '').replace(/<!--[\s\S]*?-->/g, '').replace(/\s+/g, ' ').trim();
}
const file = path.resolve(__dirname, process.argv[3] || 'index.html'), src = fs.readFileSync(file, 'utf8');
const A = '// ===== ART (generated by build-art.js) =====', B = '// ===== /ART =====';
const i = src.indexOf(A), j = src.indexOf(B);
if (i < 0 || j < 0) throw new Error('ART markers not found in index.html');
const body = 'const ART = ' + JSON.stringify(art).replace(/<\//g, '<\\/') + ';\n';
fs.writeFileSync(file, src.slice(0, i + A.length) + '\n' + body + src.slice(j));
console.log('embedded', Object.keys(art).length, 'svgs,', (body.length / 1024).toFixed(0), 'KB');

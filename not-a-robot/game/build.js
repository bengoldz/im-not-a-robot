// Builds game/dist/index.html from game/index.template.html + game/src/**/*.js + the SVG art.
//   node game/build.js            (from anywhere)
// Script order: game/src/*.js in filename order, with game/src/rounds/*.js (alphabetical) inserted just before the
// first top-level file whose name is >= "50" (so rounds load after 00..4x and before 50-cat.js, 80-ui.js, 90-main.js).
// Art: ../art/<dir>/<name>.svg -> ART["<dir>/<name>"], ../art-rig/<name>.svg -> ART["rig/<name>"],
//      game/art/<dir>/<name>.svg (optional, for new round types) -> ART["<dir>/<name>"] (added / overriding).
// The concatenated script is checked with `node --check`; any syntax error fails the build (exit code 1).
const fs = require('fs'), path = require('path'), { execFileSync } = require('child_process');
const GAME = __dirname, ROOT = path.resolve(GAME, '..'), SRC = path.join(GAME, 'src'), DIST = path.join(GAME, 'dist');
const die = msg => { console.error('\n*** BUILD FAILED ***\n' + msg + '\n'); process.exit(1); };

// ---- scripts ----
const top = fs.readdirSync(SRC).filter(f => f.endsWith('.js')).sort();
const rounds = fs.existsSync(path.join(SRC, 'rounds')) ? fs.readdirSync(path.join(SRC, 'rounds')).filter(f => f.endsWith('.js')).sort().map(f => 'rounds/' + f) : [];
let at = top.findIndex(f => f >= '50'); if (at < 0) at = top.length;
const order = [...top.slice(0, at), ...rounds, ...top.slice(at)];
let js = '';
for (const f of order) {
  const code = fs.readFileSync(path.join(SRC, f), 'utf8');
  if (/<\/script/i.test(code)) die(`src/${f} contains "</script" (would end the inline <script>); write it as "<\\/script".`);
  js += `\n// ===================== src/${f} =====================\n` + code.replace(/\s+$/, '') + '\n';
}

// ---- art ----
const art = {};
const clean = s => s.replace(/<\?xml[^>]*>/, '').replace(/<!--[\s\S]*?-->/g, '').replace(/\s+/g, ' ').trim();
function addDir(root, prefixFn) {
  if (!fs.existsSync(root)) return 0; let k = 0;
  for (const dir of fs.readdirSync(root)) {
    const d = path.join(root, dir); if (!fs.statSync(d).isDirectory()) continue;
    for (const f of fs.readdirSync(d)) if (f.endsWith('.svg')) { art[prefixFn(dir) + f.slice(0, -4)] = clean(fs.readFileSync(path.join(d, f), 'utf8')); k++; }
  }
  return k;
}
const nArt = addDir(path.join(ROOT, 'art'), dir => dir + '/');
let nRig = 0; const rigDir = path.join(ROOT, 'art-rig');
if (fs.existsSync(rigDir)) for (const f of fs.readdirSync(rigDir)) if (f.endsWith('.svg')) { art['rig/' + f.slice(0, -4)] = clean(fs.readFileSync(path.join(rigDir, f), 'utf8')); nRig++; }
const nExtra = addDir(path.join(GAME, 'art'), dir => dir + '/');
const artJs = 'const ART = ' + JSON.stringify(art).replace(/<\//g, '<\\/') + ';\n';

// ---- template ----
const tpl = fs.readFileSync(path.join(GAME, 'index.template.html'), 'utf8');
if (!tpl.startsWith('<title>')) die('index.template.html must start with <title> (artifact page contract).');
if (/<!doctype|<html[\s>]|<head[\s>]|<body[\s>]/i.test(tpl)) die('index.template.html must not contain doctype/html/head/body tags.');
const A = '// ===== ART (generated by build-art.js) =====', B = '// ===== /ART =====', P = '/*@@SCRIPTS@@*/';
const i = tpl.indexOf(A), j = tpl.indexOf(B), p = tpl.indexOf(P);
if (i < 0 || j < 0 || p < 0) die('template is missing the ART markers or the /*@@SCRIPTS@@*/ placeholder.');
const out = tpl.slice(0, i + A.length) + '\n' + artJs + tpl.slice(j, p) + js + tpl.slice(p + P.length);

// ---- syntax check of the exact inline script ----
fs.mkdirSync(DIST, { recursive: true });
const s0 = out.indexOf('<script>') + 8, s1 = out.lastIndexOf('</script>');
const checkFile = path.join(DIST, '.check.js');
fs.writeFileSync(checkFile, out.slice(s0, s1));
try { execFileSync(process.execPath, ['--check', checkFile], { stdio: 'pipe' }); }
catch (e) {
  // map the error line back to its source file
  const msg = String(e.stderr || e.message), m = msg.match(/\.check\.js:(\d+)/);
  let where = '';
  if (m) {
    const lines = out.slice(s0, s1).split('\n'), ln = +m[1];
    for (let k = ln - 1; k >= 0; k--) { const b = lines[k].match(/^\/\/ =+ src\/(\S+) =+$/); if (b) { where = `  -> src/${b[1]} line ${ln - k - 1}`; break; } }
  }
  die('node --check failed:\n' + msg + where);
}
fs.unlinkSync(checkFile);
fs.writeFileSync(path.join(DIST, 'index.html'), out);
console.log(`built dist/index.html: ${(out.length / 1024).toFixed(0)} KB, ${order.length} scripts (${order.join(', ')}), ` +
  `art ${nArt} + rig ${nRig} + extra ${nExtra}`);
